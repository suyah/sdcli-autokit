  echo "$AUTOKIT_DIR/cleanup"
}

run_sqlplus_file() {
  local base_dir="$1"
  local sqlfile="$2"
  local target_conn="$3"
  local target_user="$4"
  local target_password="$5"
  local schema_password="${6:-}"
  local prompt_count="${7:-0}"
  local current_schema="${8:-}"
  local continue_on_sql_error="${9:-false}"
  local execution_dir="${10:-$base_dir}"

  local full_path="$base_dir/$sqlfile"
  [[ -f "$full_path" ]] || return 0

  register_sqlplus_secret "target password" "$target_password"
  if [[ -n "$schema_password" ]]; then
    register_sqlplus_secret "default schema password" "$schema_password"
  fi

  log_info "Executing SQL*Plus script: $full_path"
  if $DRY_RUN; then
    log_info "+ sqlplus -S -L /nolog (connect ${target_user}/***@${target_conn}; @$full_path)"
    return 0
  fi

  local runtime_dir wrapper_file password_defines_file="" sqlplus_output_file="" rc errexit_enabled=false script_reference="$sqlfile"
  SQLPLUS_LAST_FAILURE_KIND=""
  if [[ -n "${10:-}" ]]; then
    script_reference="$full_path"
  fi
  runtime_dir="$(mktemp -d "${TMPDIR:-/tmp}/sdcli_sqlplus_XXXXXX")" || return 1
  chmod 0700 "$runtime_dir" || {
    rm -rf -- "$runtime_dir"
    return 1
  }
  register_sqlplus_runtime_dir "$runtime_dir"
  wrapper_file="$runtime_dir/wrapper.sql"
  if (( prompt_count > 0 )); then
    password_defines_file="$(create_sqlplus_password_defines "$base_dir/passworddefinition.sql" "$schema_password" "$runtime_dir")" || {
      remove_sqlplus_runtime_dir "$runtime_dir"
      return 1
    }
  fi
  {
    printf '%s\n' 'SET VERIFY OFF'
    printf '%s\n' 'WHENEVER OSERROR EXIT FAILURE;'
    if $continue_on_sql_error; then
      printf '%s\n' 'WHENEVER SQLERROR CONTINUE NONE;'
    else
      printf '%s\n' 'WHENEVER SQLERROR EXIT SQL.SQLCODE;'
    fi
    if (( prompt_count > 0 )); then
      printf '@"%s"\n' "$password_defines_file"
    fi
    if [[ -n "$current_schema" ]]; then
      printf 'alter session set current_schema = %s;\n' "$current_schema"
      printf '%s\n' 'set define off'
    fi
    printf '@"%s"\n' "$script_reference"
    if [[ -n "$current_schema" ]]; then
      printf '%s\n' 'set define on'
    fi
    printf '%s\n' 'EXIT;'
  } > "$wrapper_file" || {
    remove_sqlplus_runtime_dir "$runtime_dir"
    return 1
  }
  chmod 0600 "$wrapper_file" || {
    remove_sqlplus_runtime_dir "$runtime_dir"
    return 1
  }

  [[ "$-" == *e* ]] && errexit_enabled=true
  set +e
  if $continue_on_sql_error; then
    sqlplus_output_file="$(mktemp "${TMPDIR:-/tmp}/sdcli_sqlplus_output_XXXXXX")" || {
      $errexit_enabled && set -e
      remove_sqlplus_runtime_dir "$runtime_dir"
      SQLPLUS_LAST_FAILURE_KIND="runtime"
      return 1
    }
    (
      local connect_password
      connect_password="${target_password//\"/\"\"}"
      cd "$execution_dir"
      {
        printf 'connect %s/"%s"@%s\n' "$target_user" "$connect_password" "$target_conn"
        printf '@"%s"\n' "$wrapper_file"
      } | sqlplus -S -L /nolog
    ) 2>&1 | filter_sqlplus_deploy_output | tee "$sqlplus_output_file" | tee -a "$RUN_LOG_FILE"
    rc=${PIPESTATUS[0]}
  else
    (
      local connect_password
      connect_password="${target_password//\"/\"\"}"
      cd "$execution_dir"
      {
        printf 'connect %s/"%s"@%s\n' "$target_user" "$connect_password" "$target_conn"
        printf '@"%s"\n' "$wrapper_file"
      } | sqlplus -S -L /nolog
    ) 2>&1 | filter_sqlplus_deploy_output | tee -a "$RUN_LOG_FILE"
    rc=${PIPESTATUS[0]}
  fi
  $errexit_enabled && set -e

  remove_sqlplus_runtime_dir "$runtime_dir"
  if (( rc != 0 )); then
    SQLPLUS_LAST_FAILURE_KIND="runtime"
    rm -f "$sqlplus_output_file"
    return "$rc"
  fi
  if $continue_on_sql_error && grep -Eqi \
      '^[[:space:]]*(ORA|PLS|SP2)-[0-9]+:|^[[:space:]]*ERROR at line|[Ww]arning:.*[Cc]ompilation errors' \
      "$sqlplus_output_file"; then
    SQLPLUS_LAST_FAILURE_KIND="sql"
    rm -f "$sqlplus_output_file"
    return 1
  fi
  rm -f "$sqlplus_output_file"
  return "$rc"
}

create_sqlplus_password_defines() {
  local password_file="$1"
  local schema_password="$2"
  local runtime_dir="$3"
  local defines_file="$runtime_dir/passworddefinition.sql"
  local var escaped_password prompt_names

  [[ -f "$password_file" ]] || fail "SQL*Plus password definition file not found: $password_file"
  prompt_names="$(sqlplus_accept_prompt_names "$password_file")" || return 1

  escaped_password="${schema_password//\"/\"\"}"
  (
    umask 077
    {
      echo "-- Generated by migrate.sh for this SQL*Plus invocation."
      while IFS= read -r var; do
        [[ -n "$var" ]] || continue
        printf 'DEFINE %s = "%s"\n' "$var" "$escaped_password"
      done <<< "$prompt_names"
    } > "$defines_file"
  ) || return 1
  chmod 0600 "$defines_file" || return 1
  printf '%s\n' "$defines_file"
}

